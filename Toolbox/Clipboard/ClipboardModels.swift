import CryptoKit
import Foundation

enum ClipboardKind: String, Codable, CaseIterable, Sendable {
    case text, link, image, files, pdf
    var title: String {
        switch self { case .text: "Texto"; case .link: "Enlaces"; case .image: "Imágenes"; case .files: "Archivos"; case .pdf: "PDF" }
    }
    var symbol: String {
        switch self { case .text: "text.alignleft"; case .link: "link"; case .image: "photo"; case .files: "doc.on.doc"; case .pdf: "doc.richtext" }
    }
}

struct ClipboardRepresentation: Codable, Equatable, Sendable {
    let type: String
    let data: Data
}

struct ClipboardPart: Codable, Equatable, Sendable {
    let representations: [ClipboardRepresentation]
}

struct ClipboardContent: Codable, Equatable, Sendable {
    let items: [ClipboardPart]
    var byteCount: Int { items.flatMap(\.representations).reduce(0) { $0 + $1.data.count } }
    var types: Set<String> { Set(items.flatMap(\.representations).map(\.type)) }
    var isEmpty: Bool { items.isEmpty || items.allSatisfy { $0.representations.isEmpty } }

    static let supportedTypes: Set<String> = [
        "public.utf8-plain-text", "public.utf16-external-plain-text", "public.rtf", "com.apple.flat-rtfd", "public.html",
        "public.url", "public.file-url", "public.png", "public.tiff", "public.jpeg", "public.heic", "com.adobe.pdf"
    ]
    static let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    static let ignoredApps: Set<String> = ["com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx"]
    static let maximumCopyBytes = 25 * 1_024 * 1_024

    static func captureTypes(from offered: [String]) -> [String] {
        // Screenshots frequently advertise both a compact PNG and a very large
        // TIFF of the same pixels. Keep the lossless PNG without loading TIFF.
        let hasPNG = offered.contains("public.png")
        return offered.filter { supportedTypes.contains($0) && (!hasPNG || !["public.tiff", "public.jpeg", "public.heic"].contains($0)) }
    }

    static func mayCapture(types: Set<String>, sourceBundleID: String?) -> Bool {
        types.isDisjoint(with: ignoredTypes) && !ignoredApps.contains(sourceBundleID ?? "") && !types.isDisjoint(with: supportedTypes)
    }

    var plainText: String {
        items.compactMap { item in
            for type in ["public.utf8-plain-text", "public.utf16-external-plain-text", "public.url", "public.file-url"] {
                if let rep = item.representations.first(where: { $0.type == type }),
                   let text = String(data: rep.data, encoding: type.contains("utf16") ? .utf16 : .utf8) { return text }
            }
            return nil
        }.joined(separator: "\n")
    }

    var kind: ClipboardKind {
        if types.contains("public.file-url") { return .files }
        if !types.isDisjoint(with: ["public.png", "public.tiff", "public.jpeg", "public.heic"]) { return .image }
        if types.contains("com.adobe.pdf") { return .pdf }
        if types.contains("public.url") { return .link }
        let text = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
        if !text.contains("\n"), let url = URL(string: text), ["http", "https", "mailto"].contains(url.scheme?.lowercased() ?? "") { return .link }
        return .text
    }

    var preview: String {
        if kind == .files {
            let names = items.compactMap { item -> String? in
                guard let rep = item.representations.first(where: { $0.type == "public.file-url" }),
                      let string = String(data: rep.data, encoding: .utf8), let url = URL(string: string) else { return nil }
                return url.lastPathComponent
            }
            return names.joined(separator: ", ")
        }
        if kind == .image { return "Imagen copiada" }
        if kind == .pdf { return "Documento PDF" }
        let text = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
        return text.isEmpty ? "Texto con formato" : String(text.prefix(2_000))
    }

    var fingerprint: String {
        var hash = SHA256()
        for item in items {
            hash.update(data: Data([0xFF]))
            for rep in item.representations.sorted(by: { $0.type < $1.type }) {
                hash.update(data: Data(rep.type.utf8))
                hash.update(data: withUnsafeBytes(of: UInt64(rep.data.count).bigEndian) { Data($0) })
                hash.update(data: rep.data)
            }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

struct ClipboardEntry: Codable, Identifiable, Equatable, Sendable {
    let id: UUID
    let fingerprint: String
    var copiedAt: Date
    var sourceApp: String?
    let kind: ClipboardKind
    let preview: String
    let searchText: String
    let byteCount: Int
    let hasThumbnail: Bool

    func matches(_ query: String, kind: ClipboardKind?) -> Bool {
        (kind == nil || kind == self.kind) && (query.isEmpty || (preview + " " + searchText + " " + (sourceApp ?? "")).localizedStandardContains(query))
    }
}

struct ClipboardCaptureGate: Sendable {
    private var lastSeenCount: Int
    init(initialCount: Int) { lastSeenCount = initialCount }
    mutating func shouldRead(changeCount: Int) -> Bool {
        guard changeCount != lastSeenCount else { return false }
        lastSeenCount = changeCount
        return true
    }
    mutating func ignoreOwnWrite(changeCount: Int) { lastSeenCount = changeCount }
}

enum ClipboardHistoryNavigation {
    static func move(from selectedID: UUID?, in ids: [UUID], by offset: Int) -> UUID? {
        guard !ids.isEmpty else { return nil }
        let current = selectedID.flatMap { ids.firstIndex(of: $0) } ?? 0
        return ids[min(ids.count - 1, max(0, current + offset))]
    }
}
